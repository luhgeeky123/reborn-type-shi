# Функция для создания красивых заголовков разделов
def add_header(text):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = True
    run.size = Pt(13)
    run.font.color.rgb = RGBColor(43, 92, 143)

# Раздел 1
add_header("1. Описание предметной области и преемственность данных")
