    ["107", "Ноябрь 2025", "190 800", "Плановый незначительный рост"],
    ["108", "Декабрь 2025", "257 800", "Экстремальный пик (Сезонный фактор)"],
    ["109", "Январь 2026", "182 900", "Послепраздничный спад"],
    ["110", "Февраль 2026", "195 000", "Возврат к линии тренда"],
