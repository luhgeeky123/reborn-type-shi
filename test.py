for i, head in enumerate(headers2):
    table2.rows[0].cells[i].text = head
for row_idx, row_data in enumerate(data2):
    for col_idx, cell_data in enumerate(row_data):
        table2.rows[row_idx+1].cells[col_idx].text = cell_data

# Раздел 5 (Сюда автоматом вшивается картинка)
add_header("\n5. Визуализация данных")
doc.add_paragraph("Группировка макроэкономических показателей по пяти ценовым интервалам наглядно демонстрирует структуру распределения заработной платы в ИТ-индустрии за весь исследуемый период (114 месяцев):")

