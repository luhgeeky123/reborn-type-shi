import os
import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
import matplotlib.pyplot as plt

# 1. МАТЕМАТИЧЕСКИЙ РАСЧЕТ И ОТРИСОВКА ГИСТОГРАММЫ
intervals = ['40-80k', '80-120k', '120-160k', '160-200k', '200k+']
frequencies = [35, 30, 25, 20, 4]  # Распределение твоих 114 месяцев по интервалам

plt.figure(figsize=(7, 4.5))
bars = plt.bar(intervals, frequencies, color='#2b5c8f', edgecolor='#1a3a5c', width=0.6)

plt.title('Гистограмма распределения частот зарплат в ИТ (2017–2026 гг.)', fontsize=12, fontweight='bold', pad=15)
plt.xlabel('Интервалы заработных плат (руб.)', fontsize=10, labelpad=10)
plt.ylabel('Количество месяцев (частота)', fontsize=10, labelpad=10)
plt.grid(axis='y', linestyle='--', alpha=0.5)

# Добавляем цифры над столбиками
for bar in bars:
    yval = bar.get_height()
    plt.text(bar.get_x() + bar.get_width()/2, yval + 0.8, str(yval), ha='center', va='bottom', fontsize=10, fontweight='bold')

plt.tight_layout()
plt.savefig('histogram.png', dpi=300)
plt.close()

