for i, head in enumerate(headers1):
    table1.rows[0].cells[i].text = head
for row_idx, row_data in enumerate(data1):
    for col_idx, cell_data in enumerate(row_data):
        table1.rows[row_idx+1].cells[col_idx].text = cell_data

# Раздел 3
add_header("\n3. Первичная обработка и фильтрация данных")
doc.add_paragraph(
    "Идентификация аномалии: Значение 257 800 руб. (декабрь) резко выделяется на общем фоне. Однако, согласно выводам ЛР №1, этот всплеск не является технической ошибкой ввода. "
    "Это закономерная экономическая сезонность — выплата 13-х зарплат, годовых премий и закрытие проектных контрактов в ИТ-компаниях в конце календарного года.\n"
    "Решение по фильтрации: Для расчета чистых показателей описательной статистики (чтобы сезонные премии искусственно не завышали математическое среднее) "
    "применяется метод локального сглаживания — экстремальный пик декабря условно корректируется до медианного уровня соседних периодов (188 750 руб.)."
)

# Раздел 4
add_header("\n4. Results (Результаты расчетов статистических показателей)")

# Создаем Таблицу 2
table2 = doc.add_table(rows=6, cols=3)
table2.style = 'Light Shading Accent 1'
